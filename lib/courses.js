// اختبار تجريبي للمقررات اللي ما إلها أسئلة حقيقية بعد
export function quizFor(c) {
  const others = courses.filter((x) => x.spec !== c.spec).flatMap((x) => x.lessons);
  return c.lessons.slice(0, 3).map((l, i) => {
    const k = c.title.length;
    const d0 = others[(i * 13 + k * 3) % others.length];
    let d1 = others[(i * 29 + 7 + k) % others.length];
    if (d1 === d0) d1 = others[(i * 29 + 8 + k) % others.length];
    const o = [d0, d1];
    o.splice((i + 1) % 3, 0, l);
    return [`أي من هذه من محاور مقرر «${c.title}»؟`, o, (i + 1) % 3];
  });
}
